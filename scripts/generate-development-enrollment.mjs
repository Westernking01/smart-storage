// Offline artifact generator. Never connects to a database.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
const root = "supabase/development-cloud/";
const read = (file) => readFileSync(root + file, "utf8").replace(/\r\n/g, "\n");
const write = (file, value) => {
  if (process.argv.includes("--check")) {
    if (read(file) !== value)
      throw Error("Generated enrollment artifact drift: " + file);
  } else writeFileSync(root + file, value);
};
const source = read("enrollment-function.sql");
const body = source.split("$function$")[1];
if (!body) throw Error("Enrollment source missing");
const hash = createHash("md5").update(body).digest("hex");
const header =
  "-- Generated by scripts/generate-development-enrollment.mjs. OFFLINE CANDIDATE ONLY.\n";
const baseline = read("publisher-permissions.assert.sql");
const assertion = baseline.replace(
  "allowed text[] := ARRAY[",
  "allowed text[] := ARRAY['public.ss_dev_cloud_enrolled()',",
);
if (assertion === baseline) throw Error("Baseline assertion format changed");
const pin = `
DO $enrollment$
DECLARE p record;
BEGIN
 IF (SELECT count(*) FROM pg_catalog.pg_proc WHERE pronamespace='public'::pg_catalog.regnamespace AND proname='ss_dev_cloud_enrolled')<>1 THEN RAISE EXCEPTION 'Enrollment signature drift'; END IF;
 SELECT * INTO p FROM pg_catalog.pg_proc WHERE oid=pg_catalog.to_regprocedure('public.ss_dev_cloud_enrolled()');
 IF p.oid IS NULL OR p.prokind<>'f' OR p.pronargs<>0 OR p.prorettype<>'pg_catalog.bool'::pg_catalog.regtype OR p.proretset OR NOT p.prosecdef OR p.provolatile<>'s' OR p.proleakproof OR p.proisstrict OR p.proparallel<>'u' OR p.proowner<>'postgres'::pg_catalog.regrole OR p.prolang<>(SELECT oid FROM pg_catalog.pg_language WHERE lanname='plpgsql') OR p.proconfig IS DISTINCT FROM ARRAY['search_path=""'] OR pg_catalog.md5(pg_catalog.replace(p.prosrc,E'\\r\\n',E'\\n'))<>'${hash}' THEN RAISE EXCEPTION 'Enrollment function contract drift'; END IF;
 IF (SELECT count(*) FROM pg_catalog.aclexplode(p.proacl))<>2 OR
    NOT EXISTS(SELECT 1 FROM pg_catalog.aclexplode(p.proacl) a WHERE a.grantee='postgres'::pg_catalog.regrole AND a.grantor='postgres'::pg_catalog.regrole AND a.privilege_type='EXECUTE' AND NOT a.is_grantable) OR
    NOT EXISTS(SELECT 1 FROM pg_catalog.aclexplode(p.proacl) a WHERE a.grantee='ss_dev_cloud_publisher'::pg_catalog.regrole AND a.grantor='postgres'::pg_catalog.regrole AND a.privilege_type='EXECUTE' AND NOT a.is_grantable)
 THEN RAISE EXCEPTION 'Enrollment ACL drift'; END IF;
END $enrollment$;
`;
write("publisher-enrollment-permissions.assert.sql", header + assertion + pin);
const guard = `DO $guard$ BEGIN
 IF session_user<>'postgres' OR current_user<>'postgres' OR pg_catalog.current_setting('app.settings.project_ref',true) IS DISTINCT FROM 'fneuqneqaopkmpeevlqz' THEN RAISE EXCEPTION 'Verified project owner required'; END IF;
 IF EXISTS(SELECT 1 FROM pg_catalog.pg_stat_activity WHERE usename='ss_dev_cloud_publisher_login') THEN RAISE EXCEPTION 'Stop publisher connections first'; END IF;
END $guard$;
`;
const start =
  header +
  "\\set ON_ERROR_STOP on\nBEGIN;\nSET LOCAL lock_timeout='5s';\nSET LOCAL statement_timeout='15s';\n" +
  guard;
write(
  "install-enrollment.sql",
  start +
    `\\ir publisher-permissions.assert.sql
DO $$ BEGIN
 IF EXISTS(SELECT 1 FROM pg_catalog.pg_proc WHERE pronamespace='public'::pg_catalog.regnamespace AND proname='ss_dev_cloud_enrolled') THEN RAISE EXCEPTION 'Enrollment function already exists'; END IF;
END $$;
\\ir enrollment-function.sql
\\ir publisher-enrollment-permissions.assert.sql
COMMIT;
`,
);
write(
  "rollback-enrollment.sql",
  start +
    `\\ir publisher-enrollment-permissions.assert.sql
REVOKE EXECUTE ON FUNCTION public.ss_dev_cloud_enrolled() FROM ss_dev_cloud_publisher;
DROP FUNCTION public.ss_dev_cloud_enrolled();
\\ir publisher-permissions.assert.sql
COMMIT;
`,
);
// Explicit versioned entry points: historical baseline scripts remain strict.
for (const [input, output] of [
  [
    "publisher-preflight.readonly.sql",
    "publisher-enrollment-preflight.readonly.sql",
  ],
])
  write(
    output,
    header +
      read(input).replace(
        "\\ir publisher-permissions.assert.sql",
        "\\ir publisher-enrollment-permissions.assert.sql",
      ),
  );
